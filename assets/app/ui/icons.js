export function icon(name, { size = 16, className = "", strokeWidth = 2, label = "", ...rest } = {}) {
  const node = ICONS[name] || ICONS.help;
  const svg = s(
    "svg",
    {
      width: size,
      height: size,
      viewBox: "0 0 24 24",
      fill: "none",
      stroke: "currentColor",
      "stroke-width": strokeWidth,
      "stroke-linecap": "round",
      "stroke-linejoin": "round",
      class: `icon ${className}`.trim(),
      "aria-hidden": label ? undefined : "true",
      role: label ? "img" : undefined,
      "aria-label": label || undefined,
      focusable: "false",
      ...rest,
    },
    node.map(([tag, attrs]) => s(tag, attrs))
  );
  return svg;
}

