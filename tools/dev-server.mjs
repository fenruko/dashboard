/* Development server: static dashboard + in-memory bot API + live sockets.
 *
 * It exists so `npm run dev` gives you the whole product — real pages, real
 * requests, real websocket pushes — without a bot, a database or a Discord
 * application. Ports bind to 0.0.0.0 so sandbox/preview hosts can reach them.
 *
 *   npm run dev                 mock API + websockets (demo mode enabled)
 *   npm run dev -- --static-only   just serve files (point /config.js at a bot)
 */

import { createServer } from "node:http";
import { readFile, stat } from "node:fs/promises";
import { createReadStream } from "node:fs";
import { extname, join, normalize, resolve, sep } from "node:path";
import { WebSocketServer } from "ws";
import { createMockBackend, DEMO_USER_ID } from "./mock-backend.mjs";

const ROOT = resolve(import.meta.dirname, "..");
const PORT = Number(process.env.PORT || 4173);
const HOST = process.env.HOST || "0.0.0.0";
const STATIC_ONLY = process.argv.includes("--static-only");
const LATENCY = Number(process.env.MOCK_LATENCY ?? (STATIC_ONLY ? 0 : 40));

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
  ".well-known": "text/plain; charset=utf-8",
};

const backend = createMockBackend({ latency: LATENCY });

function runtimeConfig() {
  return `/* Generated by tools/dev-server.mjs — demo mode, same-origin API. */
window.RIFT_CONFIG = {
  apiBase: "/api",
  apiBaseFallbacks: [],
  demo: true,
  siteName: "Rift",
  discordClientId: "1329184069426348052",
};
`;
}

function json(res, status, payload, headers = {}) {
  const body = typeof payload === "string" || Buffer.isBuffer(payload) ? payload : JSON.stringify(payload);
  res.writeHead(status, {
    "Content-Type": Buffer.isBuffer(payload) ? "application/octet-stream" : "application/json; charset=utf-8",
    "Cache-Control": "no-store",
    "Access-Control-Allow-Origin": "*",
    ...headers,
  });
  res.end(body);
}

async function readBody(req) {
  const chunks = [];
  let size = 0;
  for await (const chunk of req) {
    size += chunk.length;
    if (size > 12 * 1024 * 1024) throw new Error("Body too large");
    chunks.push(chunk);
  }
  if (!chunks.length) return null;
  const text = Buffer.concat(chunks).toString("utf8");
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch {
    return text;
  }
}

function safePath(urlPath) {
  const decoded = decodeURIComponent(urlPath.split("?")[0]);
  const candidate = normalize(join(ROOT, decoded));
  if (!candidate.startsWith(ROOT + sep) && candidate !== ROOT) return null;
  return candidate;
}

async function serveStatic(req, res, urlPath) {
  let filePath = safePath(urlPath);
  if (!filePath) {
    res.writeHead(403).end("Forbidden");
    return;
  }
  let info = await stat(filePath).catch(() => null);
  if (info?.isDirectory()) {
    filePath = join(filePath, "index.html");
    info = await stat(filePath).catch(() => null);
  }
  if (!info) {
    // SPA routes (/guilds, /g/:id/..., /appeals/thread/:token) fall back to
    // index.html; missing asset files stay 404 so bugs are visible.
    if (extname(urlPath)) {
      res.writeHead(404, { "Content-Type": "text/plain" }).end("Not found");
      return;
    }
    filePath = join(ROOT, "index.html");
    info = await stat(filePath).catch(() => null);
    if (!info) {
      res.writeHead(500).end("index.html is missing");
      return;
    }
  }
  const type = MIME[extname(filePath).toLowerCase()] || "application/octet-stream";
  res.writeHead(200, {
    "Content-Type": type,
    "Cache-Control": extname(filePath) === ".html" ? "no-store" : "no-cache",
  });
  createReadStream(filePath).pipe(res);
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url || "/", `http://${req.headers.host || "localhost"}`);

  if (req.method === "OPTIONS") {
    res.writeHead(204, {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Headers": "Content-Type, Authorization, X-Idempotency-Key",
      "Access-Control-Allow-Methods": "GET, POST, PUT, PATCH, DELETE, OPTIONS",
    });
    res.end();
    return;
  }

  try {
    if (url.pathname === "/config.js" && !STATIC_ONLY) {
      res.writeHead(200, { "Content-Type": MIME[".js"], "Cache-Control": "no-store" });
      res.end(runtimeConfig());
      return;
    }

    if (url.pathname.startsWith("/api/") && !STATIC_ONLY) {
      const body = req.method === "GET" || req.method === "HEAD" ? null : await readBody(req);
      const result = await backend.handle({
        method: req.method,
        path: url.pathname,
        query: url.searchParams,
        body,
        headers: req.headers,
      });
      if (result.type !== "application/json" && result.type !== "text/plain") {
        const buffer = Buffer.isBuffer(result.body) ? result.body : Buffer.from(String(result.body));
        res.writeHead(result.status, {
          "Content-Type": result.type,
          "Content-Length": buffer.length,
          "Cache-Control": "no-store",
          "Access-Control-Allow-Origin": "*",
        });
        res.end(buffer);
        return;
      }
      json(res, result.status, result.body);
      return;
    }

    if (url.pathname === "/__mock/health" && !STATIC_ONLY) {
      json(res, 200, { ok: true, metrics: backend.metrics, user: DEMO_USER_ID });
      return;
    }

    await serveStatic(req, res, url.pathname);
  } catch (error) {
    console.error("[dev-server]", error);
    json(res, 500, { error: error?.message || "Internal mock error" });
  }
});

if (!STATIC_ONLY) {
  const wss = new WebSocketServer({ noServer: true });

  server.on("upgrade", (req, socket, head) => {
    const url = new URL(req.url || "/", `http://${req.headers.host || "localhost"}`);
    if (url.pathname !== "/ws" && url.pathname !== "/ws/vc") {
      socket.destroy();
      return;
    }
    wss.handleUpgrade(req, socket, head, (ws) => {
      if (url.pathname === "/ws/vc") attachVcSocket(ws, url);
      else attachStatsSocket(ws);
    });
  });

  function attachStatsSocket(ws) {
    let closed = false;
    const send = () => {
      if (closed) return;
      try {
        ws.send(JSON.stringify({ type: "stats", data: backend.liveStats() }));
        ws.send(JSON.stringify({ type: "music_state", guild_id: "100000000000000001", data: backend.musicState() }));
      } catch {
        /* socket died */
      }
    };
    const timer = setInterval(send, 4000);
    send();
    ws.on("message", (raw) => {
      try {
        const message = JSON.parse(String(raw));
        if (message?.type === "ping") ws.send(JSON.stringify({ type: "pong", at: Date.now() }));
      } catch {
        /* ignore malformed client frames */
      }
    });
    ws.on("close", () => {
      closed = true;
      clearInterval(timer);
    });
  }

  function attachVcSocket(ws, url) {
    let closed = false;
    const token = url.searchParams.get("access_token") || "";
    const userId = token.includes(":") ? token.split(":").pop() : DEMO_USER_ID;
    const send = () => {
      if (closed) return;
      const state = backend.callStateFor(userId);
      try {
        ws.send(JSON.stringify({ type: "call_state", data: state }));
      } catch {
        /* socket died */
      }
    };
    const timer = setInterval(send, 2500);
    send();
    ws.on("message", (raw) => {
      try {
        const message = JSON.parse(String(raw));
        if (message?.type === "get_state") send();
      } catch {
        /* ignore */
      }
    });
    ws.on("close", () => {
      closed = true;
      clearInterval(timer);
    });
  }
}

server.listen(PORT, HOST, () => {
  console.log(`Rift dashboard dev server → http://${HOST}:${PORT}/`);
  console.log(STATIC_ONLY ? "mode: static only (no mock API)" : "mode: demo API + websockets at /api, /ws, /ws/vc");
});
